# SyncSeams.py -- Regenerate seam macros from seams.yaml.
#
# Usage: python3 SyncSeams.py [seams_yaml]
#
# By default, reads seams.yaml from the same directory as this script.
#
# What it generates:
#   _Seams.h       -- SEAM macro definitions (PROJECT_CORE=1, etc.)
#   _Config.h      -- Default SEAM selection + seam list comment
#   _Main.cpp      -- TTestTree<> listing all seam test functions
#   01.Core.hxx    -- Per-seam test files (ASCIICrabs mode)
#   _Tests.hxx     -- Test tree rollup (ASCIICrabs mode)
#   <Mod>/00.Core.h -- Per-module test files (CrabsTK mode)
#
# The YAML file is the single source of truth. Never edit the generated
# files by hand -- they will be overwritten on the next sync.
#
# All generated files use angle-bracket includes (<_Config.h>, <_Seams.h>)
# so the build system controls include paths. No hardcoded relative paths.

import os
import sys
import yaml


def LoadSeams(yaml_path):
  with open(yaml_path, "r") as f:
    return yaml.safe_load(f)


def MacroName(seam_name):
  """Seam name from YAML is already the full macro (e.g. PROJECT_CORE)."""
  return seam_name.upper()


def TestFunctionName(project, seam_name):
  """PROJECT_CORE -> Core. FVM_PARSER -> Parser."""
  parts = seam_name.lower().split("_")
  if len(parts) > 1 and parts[0] == project.lower():
    parts = parts[1:]
  return "".join(p.capitalize() for p in parts)


def SeamTable(seams, release_seam):
  """Returns a list of (number, macro, is_release) tuples."""
  table = []
  for i, seam in enumerate(seams, 1):
    macro = MacroName(seam["name"])
    is_rel = seam is release_seam
    table.append((i, macro, is_rel))
  return table


def FindRelease(seams, release_name):
  for seam in seams:
    if seam["name"].upper() == release_name.upper():
      return seam
  return seams[-1]


# ---------------------------------------------------------------------------
# _Seams.h
# ---------------------------------------------------------------------------

def GenerateSeamsH(project, seams, release_seam, mode):
  lines = [
    "// Copyright AStarship <https://astarship.net>.",
    "//",
    "// AUTO-GENERATED by SyncSeams.py from seams.yaml.",
    "// Do not edit by hand -- edit seams.yaml and re-run SyncSeams.py.",
    "",
    "#pragma once",
  ]
  guard = f"{project.upper()}_SEAMS_H"
  lines.append(f"#ifndef {guard}")
  lines.append(f"#define {guard} 1")

  for i, macro, is_rel in SeamTable(seams, release_seam):
    lines.append(f"#define {macro}\t\t\t{i}")

  lines.append(f"#define SEAM_N {MacroName(release_seam['name'])}")
  lines.append("#endif")
  lines.append("")
  return "\n".join(lines)


# ---------------------------------------------------------------------------
# _Config.h (seam-level)
# ---------------------------------------------------------------------------

def GenerateConfigH(project, seams, release_seam, mode):
  release_macro = MacroName(release_seam["name"])
  lines = [
    "// Copyright AStarship <https://astarship.net>.",
    "//",
    "// AUTO-GENERATED by SyncSeams.py from seams.yaml.",
    "// Do not edit by hand -- edit seams.yaml and re-run SyncSeams.py.",
    "//",
    "// To debug a specific seam, change SEAM to that seam's macro below.",
    "// The seam at that number gets _Debug.h; all lower seams get _Release.h.",
    "// All higher seams are not compiled.",
    "",
    "#pragma once",
    "#ifndef PACKAGE_CONFIGURATION",
    "#define PACKAGE_CONFIGURATION 1",
    "#include <_Seams.h>",
    "",
    f"#define SEAM {release_macro}",
    "/* Seams:",
  ]
  for i, macro, is_rel in SeamTable(seams, release_seam):
    marker = "  (release)" if is_rel else ""
    lines.append(f"#define {macro}\t\t\t{i}{marker}")
  lines.append("*/")
  lines.append("")
  lines.append("#endif")
  lines.append("")
  return "\n".join(lines)


# ---------------------------------------------------------------------------
# _Main.cpp
# ---------------------------------------------------------------------------

