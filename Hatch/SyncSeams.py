# ---------------------------------------------------------------------------
# _Tests.hxx (ASCIICrabs mode)
# ---------------------------------------------------------------------------

def GenerateTestsHxx(project, seams, release_seam, mode):
  if mode != "asciicrabs":
    return None

  includes = "\n".join(f'#include "{seam["file"]}"' for seam in seams)
  test_fns = ", ".join(
    f"ProjectTest::{TestFunctionName(project, seam['name'])}" for seam in seams
  )

  return f"""// Copyright AStarship <https://astarship.net>.
//
// AUTO-GENERATED by SyncSeams.py from seams.yaml.
#include <_Config.h>
//
#include <_Package.hxx>
//
{includes}
//
#include <Test.hpp>
using namespace ::_;

inline const CHA* ProjectTests(const CHA* args) {{
  return TTestTree<{test_fns}>(args);
}}
"""


# ---------------------------------------------------------------------------
# Per-seam .hxx files (ASCIICrabs mode)
# ---------------------------------------------------------------------------

def GenerateCoreHxx(project, seams, release_seam, mode):
  if mode != "asciicrabs":
    return None

  templates = {}
  for i, seam in enumerate(seams):
    macro = MacroName(seam["name"])
    fn = TestFunctionName(project, seam["name"])
    label = seam.get("label", f"Testing {seam['name']}...")
    is_release = seam is release_seam

    if not is_release:
      content = f"""// Copyright AStarship <https://astarship.net>.
//
// AUTO-GENERATED by SyncSeams.py from seams.yaml.
#if SEAM >= {macro}
#if SEAM == {macro}
#include <_Debug.h>
#else
#include <_Release.h>
#endif
#endif
using namespace ::_;
namespace ProjectTest {{

inline const CHA* {fn}(const CHA* args) {{
#if SEAM >= {macro}
  A_TEST_BEGIN;

  D_COUT(Headingf("{label}"));

  // Your test code here.

#endif

  return 0;
}}

}}  //< namespace ProjectTest
"""
    else:
      content = f"""// Copyright AStarship <https://astarship.net>.
//
// AUTO-GENERATED by SyncSeams.py from seams.yaml.
#if SEAM >= {macro}
#if SEAM == {macro}
#include <_Debug.h>
#else
#include <_Release.h>
#endif
#endif
namespace ProjectTest {{

inline const CHA* {fn}(const CHA* args) {{
#if SEAM == {macro}
#endif
  return NILP;
}}

}}  //< namespace ProjectTest
"""
    templates[seam["file"]] = content

  return templates


# ---------------------------------------------------------------------------
# Per-module 00.Core.h (CrabsTK mode)
# ---------------------------------------------------------------------------

def GenerateCrabstkCoreH(project, seams, release_seam, mode):
  if mode != "crabstk":
    return None

  modules = {}
  for seam in seams:
    mod = seam.get("module", project.capitalize())
    if mod not in modules:
      modules[mod] = []
    modules[mod].append(seam)

  templates = {}
  for mod, mod_seams in modules.items():
    lines = [
      f"/* {project.upper()}",
      f"@file    /_Seams/{mod}/00.Core.h",
      f"@author  Cale McCollough <https://cookingwithcale.org>",
      f"@license Copyright 2019-20 (C) AStarship <astarship.net>; all rights",
      f"reserved (R). This Source Code Form is subject to the terms of the Mozilla",
      f"Public License, v. 2.0. If a copy of the MPL was not distributed with this file,",
      f"You can obtain one at <https://mozilla.org/MPL/2.0/>. */",
      "#pragma once",
      "#include <_Config.h>",
    ]

    # One debug/release include per seam in this module.
    for seam in mod_seams:
      macro = MacroName(seam["name"])
      lines.append(f"#if SEAM == {macro}")
      lines.append("#include <ASCIICrabs/_Debug.h>")
      lines.append(f"#elif SEAM > {macro}")
      lines.append("#include <ASCIICrabs/_Release.h>")
      lines.append("#endif")

    lines.append("#include <ASCIICrabs/Test.h>")
    lines.append("")
    lines.append("using namespace _;")
    lines.append("namespace CT {")
    lines.append(f"namespace {mod} {{")
    lines.append("namespace Test {")
    lines.append("")

    for seam in mod_seams:
      macro = MacroName(seam["name"])
      fn = TestFunctionName(project, seam["name"])
      label = seam.get("label", f"Testing {seam['name']}...")
      is_release = seam is release_seam

      lines.append(f"inline const CHA* {fn}(const CHA* args) {{")
      if not is_release:
        lines.append(f"#if SEAM >= {macro}")
        lines.append("  A_TEST_BEGIN;")
        lines.append(f'  D_COUT(Headingf("{label}"));')
        lines.append("")
        lines.append("  // Your test code here.")
        lines.append("")
        lines.append("#endif")
      else:
        lines.append(f"#if SEAM == {macro}")
        lines.append("#endif")
      lines.append("  return 0;")
      lines.append("}")
      lines.append("")

    lines.append("}  //< namespace Test")
    lines.append(f"}}  //< namespace {mod}")
    lines.append("}  //< namespace CT")
    lines.append("")
    templates[f"{mod}/00.Core.h"] = "\n".join(lines)

  return templates


# ---------------------------------------------------------------------------
# Main sync
# ---------------------------------------------------------------------------

def Sync(project_dir, yaml_path, mode):
  data = LoadSeams(yaml_path)
  project = data["project"]
  seams = data["seams"]
  release_name = data["release"]
  release_seam = FindRelease(seams, release_name)

  seams_dir = os.path.join(project_dir, "_Seams")
  os.makedirs(seams_dir, exist_ok=True)

  written = []

  def Write(rel_path, content):
    path = os.path.join(seams_dir, rel_path)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
      f.write(content)
    written.append(path)

  # _Seams.h
  Write("_Seams.h", GenerateSeamsH(project, seams, release_seam, mode))

  # _Config.h
  Write("_Config.h", GenerateConfigH(project, seams, release_seam, mode))

  # _Main.cpp
  Write("_Main.cpp", GenerateMainCpp(project, seams, release_seam, mode))

  # Mode-specific test files.
  if mode == "asciicrabs":
    content = GenerateTestsHxx(project, seams, release_seam, mode)
    if content:
      Write("_Tests.hxx", content)
    templates = GenerateCoreHxx(project, seams, release_seam, mode)
    if templates:
      for fname, fcontent in templates.items():
        Write(fname, fcontent)
  else:
    templates = GenerateCrabstkCoreH(project, seams, release_seam, mode)
    if templates:
      for fname, fcontent in templates.items():
        Write(fname, fcontent)

  print(f"Synced {len(written)} files from {os.path.basename(yaml_path)}:")
  for w in written:
    rel = os.path.relpath(w, project_dir)
    print(f"  {rel} ({os.path.getsize(w)} bytes)")

  print(f"\nSeam table:")
  for i, macro, is_rel in SeamTable(seams, release_seam):
    marker = "  (release)" if is_rel else ""
    print(f"  {i}. {macro} = {i}{marker}")


def Main():
  script_dir = os.path.dirname(os.path.abspath(sys.argv[0]))

  if len(sys.argv) >= 2:
    yaml_path = os.path.abspath(sys.argv[1])
  else:
    yaml_path = os.path.join(script_dir, "seams.yaml")

  if not os.path.exists(yaml_path):
    print(f"Error: {yaml_path} not found")
    return 1

  data = LoadSeams(yaml_path)
  project = data.get("project", "PROJECT")
  mode = data.get("mode", "asciicrabs")
  project_dir = data.get("project_dir", ".")

  if project_dir == ".":
    project_dir = os.path.dirname(os.path.abspath(yaml_path))
  elif not os.path.isabs(project_dir):
    project_dir = os.path.abspath(project_dir)

  print(f"Project: {project}")
  print(f"Mode:    {mode}")
  print(f"Dir:     {project_dir}")
  print()

  Sync(project_dir, yaml_path, mode)
  return 0


if __name__ == "__main__":
  sys.exit(Main())
