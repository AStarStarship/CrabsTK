#!/usr/bin/env python3
# Copyright AStarship <https://astarship.net>.
#
# VerifyJsx.py -- JSX regression runner (Madyar task, Gates A / D).
#
# This is a TEST SUPPORT runner, not a product module. It:
#   1. Builds ONE temporary single-TU C++ harness in the active TMPDIR that
#      #includes the durable test file (_Seams/JSX/JsxRegression.hxx) and the
#      two JSX product headers, and dispatches individual test functions by name.
#   2. Runs each test in its OWN subprocess with a timeout, so a crash or hang
#      in one crash-prone test (exhaustion / invalid handle / zero capacity) does
#      not hide the rest.
#   3. Repeats the suite in a normal build and in an ASan/UBSan build.
#   4. Runs a batch-2 OBSERVATION: emits C++ via JsxToCpp, compiles it as its own
#      TU, runs it, and compares against a directly-built tree.
#
# Python only (no shell). Compile errors are failures, not skips. Compiler
# stderr is always surfaced. Results are counted programmatically and reported
# as PASS / FAIL / BLOCKED. Exits nonzero while any required gate is incomplete.
#
# Usage:
#   python3 VerifyJsx.py [--core PATH] [--only NAME|all] [--no-sanitize]
#                        [--keep] [--json]
#
# The durable test file is discovered relative to this repo (CrabsTK). The
# ASCIICrabs core path defaults to ../ASCIICrabs and can be overridden with
# --core. Scratch is written under the active TMPDIR and is created fresh every
# run (never reused). No user files are deleted.

import argparse
import json
import os
import shutil
import subprocess
import sys
import tempfile
import textwrap

# ---------------------------------------------------------------------------
# Path discovery (relative to this repo; core path overridable).
# ---------------------------------------------------------------------------
REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))          # CrabsTK
DEFAULT_CORE = os.path.normpath(os.path.join(REPO, os.pardir, "ASCIICrabs"))

TEST_FILE = os.path.join(REPO, "_Seams", "JSX", "JsxRegression.hxx")

GXX = os.environ.get("CXX", "g++")
TIMEOUT = int(os.environ.get("JSX_TEST_TIMEOUT", "20"))       # seconds per test run
SANITIZE_TIMEOUT = int(os.environ.get("JSX_SANITIZE_TIMEOUT", "40"))
COMPILE_TIMEOUT = int(os.environ.get("JSX_COMPILE_TIMEOUT", "300"))

# Crash-prone tests are, by design, invoked one-per-subprocess; this set is
# surfaced in the report.
CRASH_PRONE = {
    "exhaustion_fails_safely",
    "invalid_handle_fails_safely",
    "zero_render_capacity",
}

# Batch-2 items gated on the (not-yet-published) builder contract. Listed here so
# the runner reports them as BLOCKED rather than silently skipping.
BATCH2_BLOCKED = [
    "includable_builder_compare (needs Mary's builder contract, Gate C)",
    "two generated builders in one TU (needs builder contract)",
    "repeated transform/render persistence + growth (needs builder contract)",
    "explicit depth/cycle limit (needs builder contract)",
    "allocation-failure cases with Illya's contract (Gate B)",
    "CodeLexer/CodeFit semantic-preservation adapter (needs stable emitted builder)",
]

# The single-TU harness the runner generates into the active TMPDIR.
HARNESS_SRC = textwrap.dedent(
    r"""
    // Auto-generated by VerifyJsx.py -- temporary single-TU harness.
    #include <_Seams.hxx>
    #include "JsxRegression.hxx"
    #include <cstdio>
    #include <cstring>
    using namespace CTK;

    static void list_tests() {
      for (const TJsxRegrEntry* e = JsxRegrEntries(); e->name; ++e)
        printf("%s\n", e->name);
    }

    // Emit C++ for argv[2] into argv[3]; report rc/length. Used for batch 2.
    static int do_emit(const char* src, const char* outpath) {
      CHA buf[16384];
      TJsxTransformResult r{};
      ISN rc = JsxToCpp(src, 0, buf, sizeof(buf), &r);
      FILE* f = fopen(outpath, "w");
      if (f) { fwrite(buf, 1, (size_t)r.output_len, f); fclose(f); }
      printf("EMIT rc=%d len=%d elements=%d errors=%d\n",
             (int)rc, (int)r.output_len, (int)r.element_count, (int)r.error_count);
      fflush(stdout);
      return (rc == 0) ? 0 : 1;
    }

    // Build the standard Welcome tree BY HAND (direct tree) and render it, so
    // the runner can compare generated-C++ output against direct tree building.
    static int do_direct() {
      static IUA buf[1 << 22];
      TJsx<ISC, ISC, DTB, CHR, CHR, IUN> j;
      j.Init(buf, ISC(1 << 22), ISC(1 << 16));
      ISC ctx = j.NewContext(ISC(16));
      j.SetVar(ctx, "name", "Captain");
      ISC el0 = j.AddObject(ISC(16384), ISC(32), ISC(2048));
      j.SetTag(el0, "Welcome");
      j.SetDynProp(el0, "name", "name");
      j.SetProp(el0, "city", "Springfield");
      j.AddText(el0, "Hello ");
      ISC el1 = j.AddObject(ISC(16384), ISC(32), ISC(2048));
      j.SetTag(el1, "b");
      j.AddText(el1, "bold");
      j.SetChild(el0, el1);
      j.AddText(el0, " world");
      CHA out[1024];
      j.Render(out, ISC(1024), ctx, el0);
      fwrite(out, 1, JsxRegrLen(out), stdout);
      fflush(stdout);
      return 0;
    }

    ISC main(int argc, char** argv) {
      const char* target = (argc > 1) ? argv[1] : "all";
      if (strcmp(target, "list") == 0) { list_tests(); return 0; }
      if (strcmp(target, "direct") == 0) { return do_direct(); }
      if (strcmp(target, "emit") == 0) {
        if (argc < 4) { printf("usage: harness emit <source> <outpath>\n"); return 2; }
        return do_emit(argv[2], argv[3]);
      }
      // Run the requested test(s) by name (or "all").
      int ran = 0, failures = 0;
      for (const TJsxRegrEntry* e = JsxRegrEntries(); e->name; ++e) {
        if (strcmp(target, "all") != 0 && strcmp(target, e->name) != 0) continue;
        ran++;
        const CHA* err = e->fn(_NilP);
        if (err) { printf("RESULT %s FAIL %s\n", e->name, err); failures++; }
        else     { printf("RESULT %s PASS\n", e->name); }
        fflush(stdout);
      }
      printf("SUMMARY ran=%d failures=%d\n", ran, failures);
      return (failures ? 1 : 0);
    }
    """
)


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------
def discover_scratch(base):
    """Create a fresh scratch dir under the active TMPDIR (never reuse stale)."""
    os.makedirs(base, exist_ok=True)
    return tempfile.mkdtemp(prefix="VerifyJsx_", dir=base)


def _dec(v):
    """Coerce a captured stream to str (subprocess text mode already yields str;
    this just silences the bytes|str union and guards None)."""
    if isinstance(v, bytes):
        return v.decode("utf-8", "replace")
    return v if v is not None else ""


def run_cmd(cmd, timeout):
    """Run a command. Returns (ok, exit, stdout, stderr, timed_out, crashed)."""
    try:
        p = subprocess.run(cmd, capture_output=True, text=False, timeout=timeout)
        return True, p.returncode, _dec(p.stdout), _dec(p.stderr), False, p.returncode < 0
    except subprocess.TimeoutExpired as e:
        return True, None, _dec(e.stdout), _dec(e.stderr), True, False
    except FileNotFoundError as e:
        return False, None, "", str(e), False, False


def tail(s, n=1200):
    s = (s or "").strip()
    return s[-n:] if len(s) > n else s


def result_line(stdout, name):
    """Find the machine line 'RESULT <name> <PASS|FAIL> [detail]' for `name`."""
    for line in (stdout or "").splitlines():
        parts = line.split(" ", 2)
        if len(parts) >= 2 and parts[0] == "RESULT" and parts[1] == name:
            status = parts[2].split(" ", 1)[0] if len(parts) > 2 else "PASS"
            detail = parts[2].split(" ", 1)[1] if (len(parts) > 2 and " " in parts[2]) else ""
            return status, detail
    return None, ""


# ---------------------------------------------------------------------------
# Build
# ---------------------------------------------------------------------------
def build_harness(scratch, core, sanitize, log_lines):
    src = os.path.join(scratch, "JsxRegressionHarness.cpp")
    out = os.path.join(scratch, "harness" + ("_asan" if sanitize else "_normal"))
    with open(src, "w") as f:
        f.write(HARNESS_SRC)
    cmd = [
        GXX, "-std=gnu++23", "-x", "c++", src,
        "-I", core,
        "-I", os.path.join(core, "_Seams"),
        "-I", os.path.join(REPO, "JSX"),
        "-I", os.path.join(REPO, "_Seams", "JSX"),
        "-DSEAM=24", "-DCRABSTK_JSX_CORE=2",
    ]
    if sanitize:
        cmd += ["-fsanitize=address,undefined", "-fno-sanitize-recover=all", "-g", "-O1"]
    else:
        cmd += ["-O1"]
    cmd += ["-o", out]
    ok, exit, _, err_s, to, _ = run_cmd(cmd, COMPILE_TIMEOUT)
    log_lines.append("$ " + " ".join(cmd))
    log_lines.append("compile exit=%s" % (exit if exit is not None else "timeout"))
    if err_s.strip():
        log_lines.append("---- compiler stderr ----")
        log_lines.append(err_s.strip())
    if not ok:
        log_lines.append("Build Failed: compiler not found (%s)" % err_s)
    elif to or exit != 0:
        log_lines.append("Build Failed (a compile error is a failure, not a skip)")
    return out if (ok and not to and exit == 0) else None


# ---------------------------------------------------------------------------
# Test execution
# ---------------------------------------------------------------------------
def run_one(harness, name, timeout):
    """Run a single test in its own subprocess; classify PASS/FAIL/BLOCKED."""
    ok, exit, out_s, err_s, to, crashed = run_cmd([harness, name], timeout)
    if not ok:
        return "FAIL", "harness could not be launched: %s" % err_s
    if to:
        return "FAIL", "did not terminate within %ds (timeout)" % timeout
    status, detail = result_line(out_s, name)
    if crashed:
        # Distinguish the known upstream UBSan misalignment from a real crash.
        blob = (err_s or "") + (out_s or "")
        if ("misalign" in blob.lower()) or ("List.hpp" in blob):
            return "BLOCKED", ("upstream misalignment in ASCIICrabs List.hpp "
                               "(UBSan baseline; recorded, not suppressed)")
        return "FAIL", "process crashed (signal %d): %s" % (abs(exit) if exit is not None else 0, tail(err_s, 400))
    if status is None:
        return "FAIL", "no RESULT line for %s (exit=%s)" % (name, exit)
    if status == "PASS":
        return "PASS", ""
    return "FAIL", (detail or "assertion failed (no detail)")


# ---------------------------------------------------------------------------
# Batch 2 observation (works on the current main-based emitter; the required
# builder-compare gate stays BLOCKED until Mary publishes the contract).
# ---------------------------------------------------------------------------
def batch2_observation(harness_normal, scratch, core, log_lines):
    """Emit C++ for a known source, compile + run it, and compare to the direct
    tree build. Returns a list of (label, status, detail) observations."""
    obs = []
    jsx = (
        "<Welcome name={name} city=\"Springfield\">"
        "Hello <b>bold</b> world"
        "</Welcome>"
    )
    expected = '<Welcome name="Captain" city="Springfield">Hello <b>bold</b> world</Welcome>'

    emitted = os.path.join(scratch, "emitted_welcome.cpp")
    ok, exit, out_s, err_s, to, _ = run_cmd([harness_normal, "emit", jsx, emitted], TIMEOUT)
    log_lines.append("$ %s emit <Welcome...> -> %s" % (os.path.basename(harness_normal), emitted))
    if out_s.strip():
        log_lines.append(tail(out_s, 300))
    if (not ok) or to or exit != 0:
        obs.append(("emit_welcome", "FAIL", "JsxToCpp emit failed (exit=%s)" % exit))
        return obs

    # Compile the emitted C++ as its own TU (it carries its own ISC main).
    out_bin = os.path.join(scratch, "emitted_welcome")
    cmd = [
        GXX, "-std=gnu++23", "-x", "c++", emitted,
        "-I", core, "-I", os.path.join(core, "_Seams"),
        "-I", os.path.join(REPO, "JSX"),
        "-DSEAM=24", "-DCRABSTK_JSX_CORE=2", "-O1", "-o", out_bin,
    ]
    ok, exit, _, err_s, to, _ = run_cmd(cmd, COMPILE_TIMEOUT)
    log_lines.append("$ " + " ".join(cmd))
    log_lines.append("emitted compile exit=%s" % (exit if exit is not None else "timeout"))
    if err_s.strip():
        log_lines.append(tail(err_s, 800))
    if not ok or to or exit != 0:
        obs.append(("generated_compile", "FAIL",
                    "emitted C++ did not compile (unescaped literal? missing header?): %s"
                    % tail(err_s, 300)))
        return obs

    ok, exit, gen_out, _, to, crashed = run_cmd([out_bin], TIMEOUT)
    if to:
        obs.append(("generated_run", "FAIL", "emitted binary did not terminate"))
        return obs
    if crashed or exit != 0:
        obs.append(("generated_run", "FAIL", "emitted binary failed (exit=%s)" % exit))
        return obs
    gen = gen_out.strip()
    obs.append(("generated_vs_expected", "OBS",
                "generated=%r expected=%r %s" % (
                    gen, expected, "" if gen == expected else "(DIVERGES)")))

    # Direct tree build for comparison.
    ok, exit, direct_out, _, to, crashed = run_cmd([harness_normal, "direct"], TIMEOUT)
    direct = (direct_out or "").strip()
    if to or crashed or exit != 0:
        obs.append(("direct_tree_render", "FAIL", "direct tree render failed (exit=%s)" % exit))
    else:
        obs.append(("generated_vs_direct", "OBS",
                    "direct=%r generated=%r %s" % (
                        direct, gen, "" if direct == gen else "(DIVERGES)")))

    # Literal edge cases: the current emitter must not emit C++ that breaks on
    # quote/backslash/newline. A compile failure here is EXPECTED evidence
    # (a finding), not a runner error.
    edge_cases = {
        "quote":     '<a x="a\"b"/>',
        "backslash": r'<a x="a\b"/>',
        "newline":   '<a x="a\nb"/>',
        "utf8":      '<a x="caf\xc3\xa9"/>',  # caf\u00e9 (UTF-8)
    }
    for label, src in edge_cases.items():
        path = os.path.join(scratch, "emitted_%s.cpp" % label)
        ok, exit, e_out, _, to, _ = run_cmd([harness_normal, "emit", src, path], TIMEOUT)
        c_out = os.path.join(scratch, "emitted_%s_bin" % label)
        ccmd = [
            GXX, "-std=gnu++23", "-x", "c++", path,
            "-I", core, "-I", os.path.join(core, "_Seams"),
            "-I", os.path.join(REPO, "JSX"),
            "-DSEAM=24", "-DCRABSTK_JSX_CORE=2", "-O1", "-o", c_out,
        ]
        cok, cexit, _, cerr, cto, _ = run_cmd(ccmd, COMPILE_TIMEOUT)
        if (not cok) or cto or cexit != 0:
            obs.append(("literal_%s" % label, "FINDING",
                        "emitted C++ for %r does not compile (literal not escaped) -- expected "
                        "until the dedicated C++-literal emitter lands" % src))
        else:
            ok2, exit2, rout, _, to2, cr2 = run_cmd([c_out], TIMEOUT)
            detail = "emitted C++ compiles and runs (out=%r)" % ((rout or "").strip())
            if to2 or cr2 or exit2 != 0:
                detail = "emitted C++ compiled but failed to run (exit=%s)" % exit2
            obs.append(("literal_%s" % label, "OBS", detail))
    return obs


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------
def parse_args():
    ap = argparse.ArgumentParser(description="JSX regression runner (Madyar).")
    ap.add_argument("--core", default=DEFAULT_CORE,
                    help="ASCIICrabs core path (default: %s)" % DEFAULT_CORE)
    ap.add_argument("--keep", action="store_true",
                    help="keep the scratch dir (print its path)")
    ap.add_argument("--only", default="all",
                    help="run only the named batch-1 test (or 'all')")
    ap.add_argument("--no-sanitize", action="store_true",
                    help="skip the ASan/UBSan build (faster; not the full gate)")
    ap.add_argument("--json", action="store_true",
                    help="also emit a machine-readable JSON summary to stdout")
    return ap.parse_args()


def run():
    args = parse_args()
    core = os.path.abspath(args.core)
    if not os.path.isdir(core):
        print("FATAL: core path does not exist: %s" % core, file=sys.stderr)
        return 2
    if not os.path.isfile(TEST_FILE):
        print("FATAL: durable test file missing: %s" % TEST_FILE, file=sys.stderr)
        return 2

    scratch_base = os.environ.get("TMPDIR") or "/tmp"
    scratch = discover_scratch(scratch_base)

    print("VerifyJsx -- JSX regression runner")
    print("  repo     : %s" % REPO)
    print("  core     : %s" % core)
    print("  testfile : %s" % TEST_FILE)
    print("  scratch  : %s" % scratch)
    print("  g++      : %s" % GXX)
    print("-" * 72)

    log_lines = []
    results_normal = []
    results_asan = []
    batch2 = []
    build_failed = False

    # --- build the normal harness ---
    harness_normal = build_harness(scratch, core, sanitize=False, log_lines=log_lines)
    if harness_normal is None:
        build_failed = True
        print("\nBuild Failed for the normal harness. Compile log:\n")
        print("\n".join(log_lines))
        finish(scratch, args.keep, log_lines, results_normal, results_asan, batch2,
               2, args.json, build_failed=True)
        return 2

    # --- discover the test names (driven by the registry, not hard-coded) ---
    ok, exit, out_s, _, to, _ = run_cmd([harness_normal, "list"], TIMEOUT)
    if (not ok) or to or exit != 0:
        print("FATAL: could not list tests from the harness (exit=%s)" % exit,
              file=sys.stderr)
        finish(scratch, args.keep, log_lines, results_normal, results_asan, batch2,
               3, args.json, build_failed=True)
        return 3
    names = [n for n in out_s.split() if n]
    print("discovered %d tests: %s\n" % (len(names), ", ".join(names)))

    # --- run each test in its own subprocess (normal build) ---
    print("== Batch 1: normal build ==")
    for name in names:
        if args.only != "all" and name != args.only:
            continue
        status, detail = run_one(harness_normal, name, TIMEOUT)
        tag = "  " if status == "PASS" else "!! "
        line = "%s%s: %s" % (tag, name, status)
        if detail:
            line += "  -- %s" % detail
        if name in CRASH_PRONE:
            line += "   [crash-prone: separate subprocess]"
        print(line)
        results_normal.append((name, status, detail))

    # --- ASan/UBSan build + per-test runs ---
    if args.no_sanitize:
        print("\n== Batch 1: ASan/UBSan build == (skipped via --no-sanitize)")
    else:
        harness_asan = build_harness(scratch, core, sanitize=True, log_lines=log_lines)
        if harness_asan is None:
            print("\nASan/UBSan build FAILED (compile log above). Sanitized runs = BLOCKED.")
            for name in names:
                if args.only != "all" and name != args.only:
                    continue
                results_asan.append((name, "BLOCKED", "sanitized build failed to compile"))
        else:
            print("\n== Batch 1: ASan/UBSan build (per-test, separate subprocess) ==")
            for name in names:
                if args.only != "all" and name != args.only:
                    continue
                status, detail = run_one(harness_asan, name, SANITIZE_TIMEOUT)
                tag = "  " if status == "PASS" else "!! "
                line = "%s%s: %s" % (tag, name, status)
                if detail:
                    line += "  -- %s" % detail
                print(line)
                results_asan.append((name, status, detail))

    # --- batch 2 observation (works on the current emitter) ---
    if args.only == "all":
        print("\n== Batch 2: generated-C++ observation (current main-based emitter) ==")
        batch2 = batch2_observation(harness_normal, scratch, core, log_lines)
        for label, status, detail in batch2:
            tag = "  " if status in ("PASS", "OBS") else "!! "
            print("%s%s: %s" % (tag, label, status))
            if detail:
                print("       %s" % detail)
    print("\nBatch 2 REQUIRED gate (includable-builder compare, 12+ nodes, two builders")
    print("one TU, persistence, depth/cycle, allocation-failure, CodeLexer/CodeFit):")
    for item in BATCH2_BLOCKED:
        print("   BLOCKED  %s" % item)

    return finish(scratch, args.keep, log_lines, results_normal, results_asan,
                  batch2, 0, args.json, build_failed=False)


def finish(scratch, keep, log_lines, results_normal, results_asan, batch2,
           base_rc, json_out, build_failed):
    """Print the programmatic tally, decide the exit code, and clean up."""
    def tally(results):
        t = {"PASS": 0, "FAIL": 0, "BLOCKED": 0}
        for _, s, _ in results:
            t[s] = t.get(s, 0) + 1
        return t

    tn = tally(results_normal)
    ta = tally(results_asan) if results_asan else None

    print("\n" + "=" * 72)
    print("TALLY (programmatic)")
    print("  normal build : PASS=%d FAIL=%d BLOCKED=%d  (total=%d)"
          % (tn["PASS"], tn["FAIL"], tn["BLOCKED"], len(results_normal)))
    if ta is not None:
        print("  asan/ubsan   : PASS=%d FAIL=%d BLOCKED=%d  (total=%d)"
              % (ta["PASS"], ta["FAIL"], ta["BLOCKED"], len(results_asan)))

    failed_normal = [n for n, s, d in results_normal if s == "FAIL"]
    failed_asan = [n for n, s, d in results_asan if s == "FAIL"]

    if log_lines:
        print("\nCompile/build log:")
        print("\n".join("  " + l for l in log_lines))

    # Exit-code policy: 0 only when every required gate is green. The baseline
    # is expected to be RED now, so nonzero is the correct, honest result.
    # Batch-2's required gate is BLOCKED, so the milestone is not complete.
    rc = base_rc
    if not build_failed:
        if failed_normal:
            rc = 1
        if ta is not None and failed_asan:
            rc = 1 if rc == 0 else rc
        if BATCH2_BLOCKED:
            rc = 1 if rc == 0 else rc

    verdict = ("BUILD/INFRASTRUCTURE FAILURE" if build_failed else
               "FAILING BASELINE (expected on current prototype)" if failed_normal else
               "GREEN" if not failed_normal else "SEE ABOVE")
    print("\nRESULT: %s  ->  exit %d" % (verdict, rc))
    print("  batch-1 required gate: %s"
          % ("complete" if (results_normal and not failed_normal) else "INCOMPLETE"))
    print("  batch-2 required gate : INCOMPLETE (blocked on builder contract)")
    print("  note: red tests here are useful evidence; they are NOT a claim that")
    print("        the JSX engine is done.")

    if json_out:
        summary = {
            "repo": REPO,
            "scratch": scratch,
            "normal": [{"name": n, "status": s, "detail": d} for n, s, d in results_normal],
            "asan": [{"name": n, "status": s, "detail": d} for n, s, d in results_asan],
            "batch2_observation": [{"name": n, "status": s, "detail": d}
                                   for n, s, d in batch2],
            "batch2_blocked": BATCH2_BLOCKED,
            "tally": {"normal": tn, "asan": ta},
            "exit": rc,
        }
        print("\nJSON SUMMARY:")
        print(json.dumps(summary, indent=2))

    if keep:
        print("\nKept scratch dir (inspect emitted C++ / logs): %s" % scratch)
    else:
        shutil.rmtree(scratch, ignore_errors=True)
    return rc


if __name__ == "__main__":
    sys.exit(run())
